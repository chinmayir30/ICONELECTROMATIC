// ==============================================================================
// seed-products-cms.mjs
// Extracts authentic 15 OEMs, 88 categories, and 169 products from catalogData.js
// and generates idempotent PostgreSQL seed commands for public.cms_content
// with key = 'products'
// ==============================================================================

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { CATALOG } from '../src/data/catalogData.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');

export function extractAuthoritativeCatalog() {
  if (!Array.isArray(CATALOG) || CATALOG.length === 0) {
    throw new Error('CATALOG data in catalogData.js is empty or invalid.');
  }

  return CATALOG.map(oem => ({
    id: oem.id,
    name: oem.name,
    shortName: oem.shortName || oem.name,
    specialty: oem.specialty || '',
    category: oem.specialty || '',
    tagline: oem.tagline || '',
    description: oem.description || '',
    website: oem.website || '',
    logoImg: oem.logoImg || '',
    logoSvg: oem.logoSvg || '',
    defaultImage: oem.defaultImage || '',
    accentColor: oem.accentColor || '#2563EB',
    glowColor: oem.glowColor || 'rgba(37,99,235,0.4)',
    visible: oem.visible !== false,
    categories: (oem.categories || []).map(cat => ({
      id: cat.id,
      name: cat.name,
      label: cat.label || '',
      description: cat.description || '',
      visible: cat.visible !== false,
      products: (cat.products || []).map(prod => ({
        id: prod.id || `${cat.id}-${Math.random().toString(36).substr(2, 6)}`,
        name: prod.name,
        category: prod.category || cat.name,
        description: prod.description || '',
        applications: prod.applications || '',
        link: prod.link || '',
        image: prod.image || oem.defaultImage || '',
        visible: prod.visible !== false,
        meta_title: prod.meta_title || `${prod.name} | ${oem.name} | Icon Electromatic`,
        meta_description: prod.meta_description || (prod.description ? prod.description.slice(0, 155) : ''),
        canonical_url: prod.canonical_url || `https://iconelectromatic.com/products/${oem.id}/${prod.id}`
      }))
    }))
  }));
}

export function generateProductSeedSql(catalog) {
  const jsonStr = JSON.stringify(catalog);
  const escapedJson = jsonStr.replace(/'/g, "''");

  let totalCategories = 0;
  let totalProducts = 0;
  catalog.forEach(o => {
    (o.categories || []).forEach(c => {
      totalCategories++;
      totalProducts += (c.products || []).length;
    });
  });

  const sql = `-- ==============================================================================
-- seed_products_cms.sql
-- Auto-generated by scripts/seed-products-cms.mjs
-- Idempotent SQL seed populating public.cms_content with key 'products'
-- Contains ${catalog.length} OEMs, ${totalCategories} Categories, and ${totalProducts} Products.
-- ==============================================================================

INSERT INTO public.cms_content (key, content, updated_at)
VALUES (
  'products',
  '${escapedJson}'::jsonb,
  timezone('utc'::text, now())
)
ON CONFLICT (key) DO UPDATE SET
  content = EXCLUDED.content,
  updated_at = EXCLUDED.updated_at;
`;

  return { sql, oemCount: catalog.length, categoryCount: totalCategories, productCount: totalProducts };
}

function run() {
  console.log('--- Generating Centralized Products Seed for public.cms_content ---');
  const catalog = extractAuthoritativeCatalog();
  const { sql, oemCount, categoryCount, productCount } = generateProductSeedSql(catalog);

  const outputPath = path.resolve(ROOT_DIR, 'supabase', 'seed_products_cms.sql');
  fs.writeFileSync(outputPath, sql, 'utf8');

  console.log(`Successfully generated ${outputPath}`);
  console.log(`Total OEMs: ${oemCount}, Total Categories: ${categoryCount}, Total Products: ${productCount}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  run();
}
